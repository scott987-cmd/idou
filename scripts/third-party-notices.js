#!/usr/bin/env node
// THIRD_PARTY_NOTICES.md: every package the application ships (the non-dev
// entries of package-lock.json) with its license, and the license text its
// author published with it. Generated, never edited by hand:
//
//   node scripts/third-party-notices.js          writes the file
//   node scripts/third-party-notices.js --check  fails when it no longer lists
//                                                exactly what the lock ships
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(root, "THIRD_PARTY_NOTICES.md");

// What the lock says the application ships, as "name@version" with its license.
export function shippedPackages(lock = JSON.parse(readFileSync(path.join(root, "package-lock.json"), "utf8"))) {
  const rows = new Map();
  for (const [where, entry] of Object.entries(lock.packages ?? {})) {
    if (!where || entry.dev || entry.link) continue;
    const name = entry.name ?? where.split("node_modules/").at(-1);
    rows.set(`${name}@${entry.version}`, { name, version: entry.version, license: entry.license ?? "UNKNOWN", where });
  }
  return [...rows.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i;
function licenseText(where) {
  const directory = path.join(root, where);
  if (!existsSync(directory)) return null;
  const files = readdirSync(directory).filter((name) => LICENSE_FILE.test(name)).sort();
  // LF throughout, as .gitattributes keeps every text file.
  return files.map((name) => readFileSync(path.join(directory, name), "utf8").replace(/\r\n?/g, "\n").trim()).join("\n\n") || null;
}

// A package's own heading is "name@version"; license texts carry headings of
// their own ("## Acceptance"), which never have that shape.
const listed = (text) => [...text.matchAll(/^## ((?:@[^/\s]+\/)?[^@\s]+@[^\s]+)$/gm)].map((match) => match[1]).sort();

if (process.argv.includes("--check")) {
  const want = shippedPackages().map((row) => `${row.name}@${row.version}`).sort();
  const have = existsSync(OUT) ? listed(readFileSync(OUT, "utf8")) : [];
  const missing = want.filter((row) => !have.includes(row)), extra = have.filter((row) => !want.includes(row));
  if (missing.length || extra.length) {
    process.stderr.write(`THIRD_PARTY_NOTICES.md 与 package-lock.json 不一致：缺 ${missing.join("、") || "无"}；多 ${extra.join("、") || "无"}。运行 node scripts/third-party-notices.js 重新生成。\n`);
    process.exit(1);
  }
  process.stdout.write(`THIRD_PARTY_NOTICES.md 列出了 ${want.length} 个随应用分发的依赖\n`);
} else if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rows = shippedPackages();
  const sections = rows.map((row) => {
    const text = licenseText(row.where);
    return `## ${row.name}@${row.version}\n\nLicense: ${row.license}\n\n${text ? "```text\n" + text.replace(/```/g, "'''") + "\n```" : "(no license file in the package; see its license field above)"}\n`;
  });
  writeFileSync(OUT, `# Third-party notices\n\nThe npm packages i豆 ships, as listed in package-lock.json, each with the license text its authors published. Generated by \`node scripts/third-party-notices.js\`; do not edit by hand. OpenAI Codex, lark-cli, Electron and Chromium are covered in NOTICE.\n\n${sections.join("\n")}`);
  process.stdout.write(`wrote ${path.relative(root, OUT)}: ${rows.length} packages\n`);
}
